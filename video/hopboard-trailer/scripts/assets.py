def write_audio(name, samples, rate=48000):
    peak = max(float(np.max(np.abs(samples))), 1e-9)
    samples = samples / max(1, peak / .85)
    with wave.open(str(AUDIO / name), 'wb') as w:
        w.setnchannels(2 if samples.ndim == 2 else 1)
        w.setsampwidth(2); w.setframerate(rate)
        w.writeframes((samples * 32767).astype('<i2').tobytes())

def score():
    sr = 48000; duration = 60
    y = np.zeros((sr * duration, 2), np.float64)
    rng = np.random.default_rng(20261030)
    # Original 120 BPM instrumental: kick, brushed snare, hats, warm bass and pad.
    for beat in range(120):
        start = beat * sr // 2
        t = np.arange(int(.3 * sr)) / sr
        kick = np.sin(2 * np.pi * (47*t + 35*.03*(1-np.exp(-t/.03)))) * np.exp(-t*19)
        kick *= .22 if beat < 20 else .30
        y[start:start+len(t)] += kick[:,None]
        if beat % 2:
            noise = rng.standard_normal(len(t))
            brushed = (noise - np.roll(noise, 1)) * np.exp(-t*40)*.035
            y[start:start+len(t)] += brushed[:,None]
        for sub in (0, 1):
            k = start + sub * sr // 4
            ht = np.arange(int(.075*sr))/sr
            noise = rng.standard_normal(len(ht))
            hat = (noise-np.roll(noise,1))*np.exp(-ht*90)*(.018 if sub else .025)
            y[k:k+len(ht),sub] += hat
        freq = [55, 43.6535, 65.4064, 49][(beat//10)%4]
        bt = np.arange(int(.43*sr))/sr
        bass = (np.sin(2*np.pi*freq*bt)+.2*np.sin(2*np.pi*freq*2*bt))*np.minimum(bt/.015,1)*np.exp(-bt*5)*.10
        y[start:start+len(bt)] += bass[:,None]
    for bar in range(0,60,5):
        t = np.arange(sr*5)/sr
        root = [220,174.614,261.626,196][(bar//5)%4]
        envelope = np.minimum(t/.6,1)*np.minimum((5-t)/.7,1)
        for ch in range(2):
            pad = sum(np.sin(2*np.pi*root*ratio*(1+ch*.0008)*t+ch*.3) for ratio in [1,1.25,1.5])/3
            y[bar*sr:(bar+5)*sr,ch] += pad*envelope*.058
    t = np.arange(sr*duration)/sr
    fade = np.minimum(t/.5,1)*np.minimum((duration-t)/2,1)
    write_audio('hopboard-original-score.wav', np.tanh(y*1.1)*fade[:,None])
    # Soft air motion: deterministic noise, no game/notification tones.
    for name,seconds in [('sweep.wav',.6),('rise.wav',1.4),('accent.wav',.8)]:
        t = np.arange(int(sr*seconds))/sr
        noise = rng.standard_normal(len(t))
        smooth = np.convolve(noise,np.ones(12)/12,mode='same')
        env = np.sin(np.pi*t/seconds)**2
        if name=='accent.wav':
            sig = .19*np.sin(2*np.pi*(55*t+18*.025*(1-np.exp(-t/.025))))*np.exp(-t*11)+smooth*.045*np.exp(-t*8)
        else: sig = smooth*env*.18
        write_audio(name,sig)
    t=np.arange(int(sr*.055))/sr
    click=(rng.standard_normal(len(t))*.045+np.sin(2*np.pi*1300*t)*.04)*np.exp(-t*160)
    write_audio('click.wav',click)
    (ROOT/'audio-provenance.json').write_text(json.dumps({'score':'Original procedural composition generated by scripts/assets.py; 120 BPM; beat0=0; no external samples','sfx':'Original seeded air/impact/click synthesis, not notification tones','narration':'Microsoft Edge online neural voice en-US-GuyNeural; only fictional product marketing text sent','seed':20261030,'duration':60,'sampleRate':sr},indent=2))

async def narration():
    import edge_tts
    results=[]
    for i,line in enumerate(LINES):
        path=AUDIO/f'voice-{i:02}.mp3'
        if not path.exists():
            await edge_tts.Communicate(line,'en-US-GuyNeural',rate='+7%').save(str(path))
        seconds=float(subprocess.check_output(['ffprobe','-v','quiet','-show_entries','format=duration','-of','csv=p=0',str(path)],text=True))
        if seconds>4.65:
            temp=AUDIO/f'voice-{i:02}-fit.mp3'
            subprocess.run(['ffmpeg','-v','error','-y','-i',str(path),'-af',f'atempo={seconds/4.55:.6f}',str(temp)],check=True)
            temp.replace(path)
            seconds=float(subprocess.check_output(['ffprobe','-v','quiet','-show_entries','format=duration','-of','csv=p=0',str(path)],text=True))
        results.append({'scene':i,'text':line,'duration':seconds,'fromFrame':i*150+8})
        print(f'Voice {i}: {seconds:.2f}s',flush=True)
    (ROOT/'narration.json').write_text(json.dumps(results,indent=2))

def crops():
    boxes={
      'pair-card':('pairing',(505,45,430,810)),
      'auto-control':('clipboard',(120,240,1200,100)),
      'text-card':('clipboard',(120,452,832,330)),
      'device-list':('devices',(120,205,1200,540)),
      'file-card':('files',(120,452,832,330)),
    }
    data={}
    for key,(source,(x,y,w,h)) in boxes.items():
        image=Image.open(PUBLIC/'textures'/f'{source}.png')
        image.crop((x*2,y*2,(x+w)*2,(y+h)*2)).save(PUBLIC/'textures'/f'{key}.png')
        data[key]={'source':source,'x':x,'y':y,'w':w,'h':h,'pixelRatio':2}
    Image.open(PUBLIC/'textures/join-code.png').crop((992,448,1888,1352)).save(PUBLIC/'textures/join-dialog.png')
    Image.open(PUBLIC/'textures/pairing.png').crop((1010,90,1870,770)).save(PUBLIC/'textures/host-code.png')
    (PUBLIC/'textures/layout.json').write_text(json.dumps({'pageW':1440,'pageH':900,'pixelRatio':2,'elements':data},indent=2))

if __name__=='__main__':
    score(); crops(); asyncio.run(narration())
